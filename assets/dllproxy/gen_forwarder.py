"""Generate a full forwarder for an app-local proxy DLL (a shim that replaces a system DLL by name).

    python3 -I gen_forwarder.py EXPORTS DLLNAME OUTDIR
    e.g. python3 -I gen_forwarder.py dbghelp.exports dbghelp.dll .

EXPORTS: one export name per line, as printed by scripts/pe/exports.py for Wine's builtin
(`lib/wine/x86_64-windows/<dll>` of the engine the game runs on). Writes into OUTDIR:
  forward_thunks.S   one 6-byte `jmp *slot(%rip)` per export, the slot table (fwd_slots, all
                     pointing at fwd_missing until forward.c fills them), fwd_names and fwd_count
  <base>.def         LIBRARY <dllname> + every export
A jump keeps every register and the stack as the caller left them, so any signature and calling
convention works (x86-64 only). Data exports are not supported: check the builtin has none.
Build with forward.c and the shim's own source, e.g.
  x86_64-w64-mingw32-gcc -O2 -shared -o dbghelp.dll shim.c forward.c forward_thunks.S dbghelp.def -luser32
"""
import sys
from pathlib import Path

exports, dllname, outdir = Path(sys.argv[1]), sys.argv[2], Path(sys.argv[3])
names = []
for line in exports.read_text().splitlines():
    if not line.strip():
        continue
    if "->" in line or line.startswith("@"):
        sys.exit(f"unsupported export line (forwarder or ordinal-only): {line}")
    names.append(line.split()[0])

asm = [f"# generated by gen_forwarder.py from {exports.name}: do not edit", "\t.text"]
for i, n in enumerate(names):
    asm += [f"\t.globl {n}", f"\t.def {n}; .scl 2; .type 32; .endef", f"{n}:",
            f"\tjmp *fwd_slots+{8 * i}(%rip)"]
asm += ["", "\t.data", "\t.p2align 3", "\t.globl fwd_slots", "fwd_slots:"]
asm += ["\t.quad fwd_missing" for _ in names]
asm += ["", "\t.section .rdata,\"dr\"", "\t.p2align 3", "\t.globl fwd_names", "fwd_names:"]
asm += [f"\t.quad fwd_name_{i}" for i in range(len(names))]
asm += ["\t.globl fwd_count", "\t.p2align 2", "fwd_count:", f"\t.long {len(names)}"]
asm += [f"fwd_name_{i}:\t.asciz \"{n}\"" for i, n in enumerate(names)]
(outdir / "forward_thunks.S").write_text("\n".join(asm) + "\n")

base = dllname[:-4] if dllname.lower().endswith(".dll") else dllname
(outdir / f"{base}.def").write_text(f"LIBRARY {dllname}\nEXPORTS\n" + "".join(f"{n}\n" for n in names))
print(f"{len(names)} exports -> {outdir / 'forward_thunks.S'}, {outdir / (base + '.def')}")
